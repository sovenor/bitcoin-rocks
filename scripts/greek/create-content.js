function createFile(enFileName, elFileName, greekOverrides) {
	const enSrc = JSON.parse(fs.readFileSync(path.join(i18nDir, 'en', enFileName), 'utf8'));
	const final = {"@metadata": { "authors": ["Satoshi"], "last-updated": today, "locale": lang }};
	for (const [key, val] of Object.entries(enSrc)) {
		if (key === '@metadata') continue;
		final[key] = greekOverrides[key] || val;
	}
	const filePath = path.join(i18nDir, lang, elFileName);
	fs.mkdirSync(path.dirname(filePath), { recursive: true });
	fs.writeFileSync(filePath, JSON.stringify(final, null, '\t') + '\n', 'utf8');
	console.log(`CREATED: ${filePath} (${Object.keys(final).length - 1} keys)`);
}

